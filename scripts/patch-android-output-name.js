#!/usr/bin/env node
/*
 * Give the built Android artefacts a name that says what they are.
 *
 * Gradle writes `app-release.apk` and `app-release.aab` whatever the app is and
 * whatever version it carries. Three of those on a desktop are indistinguishable,
 * and the one you send a vessel is the one you happen to click. After this they
 * are named for the app, the version and the day they were built:
 *
 *     MSM-2.51-20260930.apk
 *     MSM-2.51-20260930-release.aab      (Gradle adds the build type for bundles)
 *     MSM-2.51-20260930-debug.apk
 *
 * `android/` is CNG (gitignored, regenerated by prebuild), so this is re-applied
 * from `postinstall` like the other android patches. Idempotent.
 *
 * Run manually after a prebuild:  node scripts/patch-android-output-name.js
 */
const fs = require('fs');
const path = require('path');

const gradle = path.join(__dirname, '..', 'android', 'app', 'build.gradle');
if (!fs.existsSync(gradle)) process.exit(0); // managed / not prebuilt yet

const MARKER = 'msmArtefactBase';
let src = fs.readFileSync(gradle, 'utf8');
if (src.includes(MARKER)) process.exit(0); // already patched

const ANCHOR = '\n    signingConfigs {';
if (!src.includes(ANCHOR)) {
  console.warn('[patch-android-output-name] signingConfigs block not found — skipped');
  process.exit(0);
}

// The date is taken when GRADLE runs, not when this script does: a prebuild from
// last week must not stamp today's build with last week's date.
const BLOCK = `
    // ---- artefact naming (scripts/patch-android-output-name.js) ------------
    // MSM-<version>-<yyyymmdd>.apk instead of app-release.apk, so a build can be
    // identified from its filename alone — which is how it reaches a vessel.
    def msmBuildStamp = new java.text.SimpleDateFormat('yyyyMMdd').format(new java.util.Date())
    def msmArtefactBase = "MSM-\${defaultConfig.versionName}-\${msmBuildStamp}"
    base {
        // Names the .aab; Gradle appends the build type ("-release.aab").
        archivesName = msmArtefactBase
    }
    applicationVariants.all { variant ->
        // Release is the one that travels, so it carries no build-type suffix;
        // anything else says so, because a debug build must never be mistaken
        // for the one sent to a ship.
        def msmSuffix = variant.buildType.name == 'release' ? '' : "-\${variant.buildType.name}"
        variant.outputs.all { output ->
            outputFileName = "MSM-\${variant.versionName}-\${msmBuildStamp}\${msmSuffix}.apk"
        }
    }
`;

src = src.replace(ANCHOR, BLOCK + ANCHOR);
fs.writeFileSync(gradle, src);
console.log('[patch-android-output-name] APK/AAB will be named MSM-<version>-<date>');
