#!/usr/bin/env node
/*
 * Keep MainActivity alive across fold / unfold (foldables, Surface Duo).
 *
 * Opening a foldable or spanning the Duo changes the SMALLEST screen width
 * (cover ~360dp → inner ~700dp+). Expo's template lists orientation, screenSize
 * and screenLayout in android:configChanges but not smallestScreenSize or
 * density, so Android destroyed and recreated the activity on every fold —
 * React Native restarted from the splash, the open screen and any half-filled
 * form were gone, and on some devices the app did not come back at all.
 * With them listed, RN just receives a Dimensions 'change' and re-lays out
 * (utils/orientation.ts re-applies the portrait/rotate policy on it).
 *
 * `android/` is CNG (regenerated by prebuild), so this re-applies from
 * `postinstall` and `npm run aab`. Idempotent — no-ops when android/ is absent
 * or already patched.
 *
 * Run manually after a prebuild:  node scripts/patch-android-foldable.js
 */
const fs = require('fs');
const path = require('path');

const manifest = path.join(__dirname, '..', 'android', 'app', 'src', 'main', 'AndroidManifest.xml');
if (!fs.existsSync(manifest)) process.exit(0); // managed / not prebuilt yet

const NEEDED = ['smallestScreenSize', 'density'];
let s = fs.readFileSync(manifest, 'utf8');
const re = /(<activity[^>]*android:name="\.MainActivity"[^>]*android:configChanges=")([^"]*)(")/;
const m = s.match(re);
if (!m) {
  console.warn('[patch-android-foldable] MainActivity configChanges not found — not patched');
  process.exit(0);
}
const have = m[2].split('|');
const add = NEEDED.filter((k) => !have.includes(k));
if (!add.length) process.exit(0); // already patched

s = s.replace(re, `$1${[...have, ...add].join('|')}$3`);
fs.writeFileSync(manifest, s);
console.log(`[patch-android-foldable] configChanges += ${add.join('|')}`);
