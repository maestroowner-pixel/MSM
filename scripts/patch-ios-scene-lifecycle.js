#!/usr/bin/env node
/**
 * UIScene life cycle — without this the app does not launch on iOS 26/27.
 *
 * WHAT HAPPENS WITHOUT IT. An app LINKED AGAINST the iOS 26+ SDK (i.e. built
 * with Xcode 26/27) that does not declare `UIApplicationSceneManifest` is killed
 * by UIKit during startup, before `application:didFinishLaunchingWithOptions:`
 * ever runs. The crash report says
 *
 *     EXC_BREAKPOINT … UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption
 *
 * and nothing in the app's own code appears in the trace, because none of it has
 * run yet. Reported from a vessel on 29 Sep 2026: MSM 2.46 would not open at all
 * on an iPhone updated to iOS 27. It is not a device setting and not a bad
 * install — the build itself has to adopt the scene life cycle.
 *
 * THE MANIFEST ALONE IS NOT ENOUGH, and that is the trap. Declare the manifest
 * and the app launches into a BLACK SCREEN: UIKit now expects a scene to own the
 * window, while Expo's AppDelegate is still creating one against
 * `UIScreen.main.bounds` and attaching it to nothing. So window creation and the
 * React Native start-up have to move into the scene delegate, which is what this
 * script does:
 *
 *   - `didFinishLaunchingWithOptions` keeps the factory wiring and only REMEMBERS
 *     the launch options;
 *   - `SceneDelegate.scene(_:willConnectTo:options:)` builds the window against
 *     the window scene, starts React Native in it, and replays the cold-start
 *     URLs and user activities that used to arrive through the AppDelegate.
 *
 * WHY A SCRIPT AND NOT AN EDIT. `ios/` is CNG — generated by `expo prebuild` and
 * gitignored — so a hand-edited AppDelegate.swift is deleted the next time
 * anybody regenerates it, which is exactly when the fix would be least noticed.
 * This runs from `postinstall` alongside the other patch-*.js, is idempotent, and
 * says plainly when there is nothing to do.
 *
 * WHEN TO DELETE THIS. Expo adopts the scene life cycle itself from SDK 57.0.23.
 * On an SDK upgrade, check whether the generated AppDelegate already carries a
 * scene delegate; if it does, remove this script rather than patching a file
 * that no longer needs it.
 */

const fs = require('fs');
const path = require('path');

const APP_DELEGATE = path.join(__dirname, '..', 'ios', 'MarineSafetyManager', 'AppDelegate.swift');

const MARKER = '// --- UIScene life cycle (scripts/patch-ios-scene-lifecycle.js) ---';

const SCENE_DELEGATE = `
${MARKER}
//
// Required by iOS 26+: an app built against that SDK without a scene delegate is
// terminated by UIKit at launch. The window is created HERE, against the window
// scene, because a window made from UIScreen.main.bounds belongs to no scene and
// shows as black.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate,
          let factory = appDelegate.reactNativeFactory else {
      return
    }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    // The AppDelegate still holds a reference: parts of React Native and of the
    // Expo modules read \`UIApplication.shared.delegate.window\`.
    appDelegate.window = window

    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: appDelegate.launchOptions)

    // A cold start from a msm:// label, a widget or a universal link arrives on
    // the scene rather than through the AppDelegate, and would otherwise be lost
    // — which is precisely the "scan a QR code, the app opens on the dashboard"
    // bug this would have caused.
    for context in connectionOptions.urlContexts {
      RCTLinkingManager.application(UIApplication.shared, open: context.url, options: [:])
    }
    for activity in connectionOptions.userActivities {
      RCTLinkingManager.application(UIApplication.shared, continue: activity, restorationHandler: { _ in })
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      RCTLinkingManager.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    RCTLinkingManager.application(UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

function main() {
  if (!fs.existsSync(APP_DELEGATE)) {
    console.log('[scene] ios/ not generated yet — nothing to patch (run expo prebuild first).');
    return;
  }

  let src = fs.readFileSync(APP_DELEGATE, 'utf8');
  if (src.includes(MARKER)) {
    console.log('[scene] AppDelegate.swift already adopts the UIScene life cycle.');
    return;
  }

  // 1. Remember the launch options — the scene needs them, and it runs later.
  if (!src.includes('var launchOptions:')) {
    src = src.replace(
      /(var reactNativeFactory: RCTReactNativeFactory\?\n)/,
      '$1  /// Held for SceneDelegate, which starts React Native once the scene exists.\n' +
        '  var launchOptions: [UIApplication.LaunchOptionsKey: Any]?\n'
    );
  }

  // 2. Hand window creation and the React Native start-up to the scene.
  const startBlock =
    /#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n\s*factory\.startReactNative\(\s*\n\s*withModuleName: "main",\s*\n\s*in: window,\s*\n\s*launchOptions: launchOptions\)\s*\n\s*#endif/;
  if (!startBlock.test(src)) {
    console.error(
      '[scene] Could not find the window/startReactNative block in AppDelegate.swift.\n' +
        '        Expo probably changed the template — re-check this script against it\n' +
        '        BEFORE shipping an iOS build, or the app will not launch on iOS 26+.'
    );
    process.exitCode = 1;
    return;
  }
  src = src.replace(
    startBlock,
    '    // The window is created by SceneDelegate — see the bottom of this file.\n' +
      '    self.launchOptions = launchOptions'
  );

  // 3. Append the scene delegate itself.
  src = src.trimEnd() + '\n' + SCENE_DELEGATE;

  fs.writeFileSync(APP_DELEGATE, src);
  console.log('[scene] AppDelegate.swift now adopts the UIScene life cycle.');
}

main();
