#!/usr/bin/env node
/*
 * Give Gradle enough METASPACE to finish a release build.
 *
 * THE FAILURE THIS FIXES:
 *   > Task :expo:lintVitalAnalyzeRelease FAILED
 *   java.lang.OutOfMemoryError: Metaspace
 *
 * Expo's generated gradle.properties ships `-Xmx2048m -XX:MaxMetaspaceSize=512m`.
 * Heap is not the problem — metaspace is. Android Lint's vital analysis loads the
 * class metadata of the whole app plus every dependency into a single daemon, and
 * this project carries a lot of them (RN 0.81, ~40 Expo modules, Firebase). 512 MB
 * of class metadata is simply not enough, and the daemon dies partway through with
 * no hint that memory is what it wanted.
 *
 * Note it fails at RELEASE only: `lintVitalAnalyzeRelease` does not run for a debug
 * build, which is why `expo run:android` is fine and `npm run aab` is not.
 *
 * The numbers are sized for a development Mac (this one has 24 GB), not for a small
 * CI box — if a runner has less, lower them there rather than here.
 *
 * `android/` is CNG and regenerated by prebuild, so this re-applies from
 * `postinstall`. Idempotent. Run manually after a prebuild:
 *   node scripts/patch-android-memory.js
 */
const fs = require('fs');
const path = require('path');

const gp = path.join(__dirname, '..', 'android', 'gradle.properties');
if (!fs.existsSync(gp)) process.exit(0); // managed / not prebuilt yet

const WANT = 'org.gradle.jvmargs=-Xmx6144m -XX:MaxMetaspaceSize=2048m';

let s = fs.readFileSync(gp, 'utf8');
if (s.includes(WANT)) process.exit(0); // already patched

const line = /^org\.gradle\.jvmargs=.*$/m;
if (line.test(s)) {
  s = s.replace(line, WANT);
} else {
  s = s.trimEnd() + '\n\n' + WANT + '\n';
}

fs.writeFileSync(gp, s);
console.log('[patch-android-memory] gradle.jvmargs -> -Xmx6144m -XX:MaxMetaspaceSize=2048m');
