#!/usr/bin/env node
/*
 * Strip deprecated edge-to-edge window APIs from the Android theme after
 * `expo prebuild`.
 *
 * The RN template always writes `android:statusBarColor` and
 * `android:enforceNavigationBarContrast` into android/app/src/main/res/values/
 * styles.xml. On Android 15 (targetSdk 35+) these map to the DEPRECATED
 * Window.setStatusBarColor() / setNavigationBarContrastEnforced() APIs, which
 * Google Play flags ("unsupported edge-to-edge APIs"). Edge-to-edge is already
 * enabled (app.json android.edgeToEdgeEnabled) and system-enforced on 15+, so
 * these attributes are no-ops that only trigger the warning — remove them.
 *
 * android/ is CNG (regenerated by prebuild), so this re-applies on every
 * prebuild. Idempotent — runs from `postinstall` and before the release bundle
 * (no-ops when android/ is absent or already patched).
 *
 * Run manually after a prebuild:  node scripts/patch-android-edge-to-edge.js
 */
const fs = require('fs');
const path = require('path');

const androidDir = path.join(__dirname, '..', 'android');
if (!fs.existsSync(androidDir)) process.exit(0); // managed / not prebuilt yet

const stylesFiles = [
  path.join(androidDir, 'app/src/main/res/values/styles.xml'),
  path.join(androidDir, 'app/src/main/res/values-night/styles.xml'),
];

// Any <item name="android:statusBarColor|android:navigationBarColor|
// android:enforceNavigationBarContrast|android:enforceStatusBarContrast">…</item>
const DEPRECATED = /^\s*<item name="android:(statusBarColor|navigationBarColor|enforceNavigationBarContrast|enforceStatusBarContrast)"[^>]*>.*<\/item>\s*\r?\n/gm;

for (const file of stylesFiles) {
  if (!fs.existsSync(file)) continue;
  const before = fs.readFileSync(file, 'utf8');
  const after = before.replace(DEPRECATED, '');
  if (after !== before) {
    fs.writeFileSync(file, after);
    console.log(`[patch-android-edge-to-edge] removed deprecated window attrs from ${path.relative(androidDir, file)}`);
  }
}
