#!/usr/bin/env node
// ===================================
// Raise every Pod's IPHONEOS_DEPLOYMENT_TARGET to the app's own (15.1).
//
// Xcode 27 refuses to build a target whose deployment target is below 15.0
// ("the range of supported deployment target versions is 15.0 to 27.0.x"), and
// several pods still declare 9.0–13.4 in their podspecs (SDWebImage, RNSVG,
// RNCAsyncStorage, RevenueCat…). Older Xcodes only warned. The app itself is
// 15.1 (Podfile `platform :ios`), so lifting the pods to it changes nothing
// about what devices are supported — it only tells Xcode what was already true.
//
// Written into ios/Podfile's post_install. ios/ is CNG (regenerated by prebuild),
// so this runs from postinstall like the other patches and is idempotent.
//   node scripts/patch-ios-deployment-target.js
// then `cd ios && pod install`.
// ===================================
const fs = require('fs');
const path = require('path');

const podfile = path.join(__dirname, '..', 'ios', 'Podfile');
if (!fs.existsSync(podfile)) {
  console.log('[patch-ios-deployment-target] no ios/Podfile — skipped (run expo prebuild first)');
  process.exit(0);
}
let src = fs.readFileSync(podfile, 'utf8');
const MARK = '# msm: pods below the app deployment target';
if (src.includes(MARK)) {
  console.log('[patch-ios-deployment-target] already applied');
  process.exit(0);
}
const anchor = /(    react_native_post_install\([\s\S]*?\n    \)\n)/;
if (!anchor.test(src)) {
  console.error('[patch-ios-deployment-target] post_install block not found — Podfile layout changed?');
  process.exit(1);
}
const block = `$1    ${MARK} (Xcode 27 refuses them; see scripts/patch-ios-deployment-target.js)
    min_ios = Gem::Version.new(podfile_properties['ios.deploymentTarget'] || '15.1')
    installer.pods_project.targets.each do |t|
      t.build_configurations.each do |c|
        cur = c.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        c.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = min_ios.to_s if cur.nil? || Gem::Version.new(cur) < min_ios
      end
    end
`;
src = src.replace(anchor, block);
fs.writeFileSync(podfile, src);
console.log('[patch-ios-deployment-target] Podfile patched — run: cd ios && pod install');
