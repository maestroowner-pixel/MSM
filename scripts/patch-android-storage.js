#!/usr/bin/env node
/*
 * Raise AsyncStorage's Android database ceiling after `expo prebuild`.
 *
 * WHY THIS EXISTS. @react-native-async-storage/async-storage is backed by SQLite
 * on Android and ships with a **6 MB** default cap. Everything the app stores
 * lives in it, and until inspections that was fine — a register is bounded by
 * how much equipment the vessel has, and 627 items is well under a megabyte.
 *
 * The inspection trail is not bounded that way: it is append-only and grows for
 * as long as the vessel runs. A ship inspecting ~600 items monthly writes on the
 * order of 2 MB a year, so a 6 MB cap is roughly a three-year fuse — and it does
 * not fail with a dialog, it fails as a write that silently throws. On an audit
 * trail, silently dropping the newest records is the worst possible failure.
 *
 * 50 MB is far past anything the app can realistically produce (decades), costs
 * nothing when unused (SQLite grows on demand), and moves the failure mode from
 * "loses data in year three" to "never".
 *
 * `android/` is CNG (regenerated by prebuild), so this re-applies from
 * `postinstall`. Idempotent — no-ops when android/ is absent or already patched.
 *
 * Run manually after a prebuild:  node scripts/patch-android-storage.js
 */
const fs = require('fs');
const path = require('path');

const androidDir = path.join(__dirname, '..', 'android');
if (!fs.existsSync(androidDir)) process.exit(0); // managed / not prebuilt yet

const gp = path.join(androidDir, 'gradle.properties');
if (!fs.existsSync(gp)) process.exit(0);

let s = fs.readFileSync(gp, 'utf8');
if (s.includes('AsyncStorage_db_size_in_MB')) process.exit(0); // already patched

s =
  s.trimEnd() +
  '\n\n' +
  '# AsyncStorage ceiling. The default is 6 MB; the append-only inspection trail\n' +
  '# grows for the life of the vessel and would silently hit it. See\n' +
  '# scripts/patch-android-storage.js for the arithmetic.\n' +
  'AsyncStorage_db_size_in_MB=50\n';

fs.writeFileSync(gp, s);
console.log('[patch-android-storage] AsyncStorage_db_size_in_MB=50 written to gradle.properties');
